// Writes src/content/docs/guides/examples.md from src/data/examples.ts. Run it after changing the data:
//   npm run examples-page
import { writeFileSync } from 'node:fs';
import { exampleGuides, exampleLanguages, fileUrl, repoUrl } from '../src/data/examples.ts';

const repos = exampleLanguages
	.map((l) => `| ${l.label} | [${l.repo}](${repoUrl(l)}) | ${l.needs} | \`${l.run}\` |`)
	.join('\n');

const rows = exampleGuides
	.map((g) => {
		const links = exampleLanguages.flatMap((l) => {
			const file = l.file(g.slug);
			return file ? [`[${l.label}](${fileUrl(l, file)})`] : [];
		});
		return `| [${g.title}](${g.href}) | ${links.join(' · ')} |`;
	})
	.join('\n');

writeFileSync(
	new URL('../src/content/docs/guides/examples.md', import.meta.url),
	`---
title: Runnable examples
description: The code from every guide as programs you can clone and run, in each language. One repo per language.
sidebar:
  label: Runnable examples
---
<!-- Generated by scripts/examples-page.ts from src/data/examples.ts; do not edit by hand. -->

The code in each guide's tabs is also a program you can run. Each language has a repo with one file per
guide and a shared setup that signs in from \`OV_EMAIL\`, \`OV_PASSWORD\` and \`OV_SECRET_KEY\`. CI builds
or type-checks every example against the released packages on every change and each week.

Running an example does something safe and mostly read-only. The calls that change an account for good
(deleting it, revoking access, rotating keys) are there to read and copy. Try the rest on a test account.

## The repos

| Language | Repo | You need | Run the first program |
|---|---|---|---|
${repos}

Every repo also has a \`check\` example that reaches the account server without signing in, to test the
setup.

## By guide

| Guide | Example |
|---|---|
${rows}

The ov CLI has scripts for the guides that have an **ov CLI** tab, plus \`ov inject\` and \`ov run\`
templates and a GitHub Actions workflow in [\`examples/ci/\`](https://github.com/openvireo/openvireo-examples-cli/tree/main/examples/ci).
`,
);
