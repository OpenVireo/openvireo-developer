import type { APIRoute, GetStaticPaths } from 'astro';
import { getCollection, type CollectionEntry } from 'astro:content';

// Every docs page as Markdown at <path>.md, for "Copy as Markdown" and AI tools (see llms.txt).
export const getStaticPaths = (async () => {
	const docs = await getCollection('docs');
	return docs
		.filter((entry) => entry.id !== 'index' && entry.body)
		.map((entry) => ({ params: { slug: entry.id }, props: { entry } }));
}) satisfies GetStaticPaths;

export const GET: APIRoute = ({ props }) => {
	const { entry } = props as { entry: CollectionEntry<'docs'> };
	const body = (entry.body ?? '')
		.replace(/^<!-- Generated by [^\n]*-->\n+/m, '')
		.replace(/^import [^\n]*\n/gm, '');
	const lead = entry.data.description ? `\n${entry.data.description}\n` : '';
	return new Response(`# ${entry.data.title}\n${lead}\n${body.trim()}\n`, {
		headers: { 'Content-Type': 'text/markdown; charset=utf-8' },
	});
};
